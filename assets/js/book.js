const flat = [];
VOLUMES.forEach(v => v.chapters.forEach(c => flat.push({...c, vol:v.vol})));
const STORE = "utyos_played_v1";
let played = new Set(JSON.parse(localStorage.getItem(STORE) || "[]"));
let cur = 0;
const $ = s => document.querySelector(s);
const toc = $("#toc"), page = $("#page");

function buildTOC(){
  toc.innerHTML = "";
  VOLUMES.forEach(v=>{
    const h = document.createElement("div"); h.className="vol"; h.textContent=v.vol; toc.appendChild(h);
    v.chapters.forEach(c=>{
      const idx = flat.indexOf(c);
      const a = document.createElement("a");
      a.dataset.idx = idx; a.dataset.played = played.has(idx) ? "1" : "";
      if(played.has(idx)) a.classList.add("played");
      a.innerHTML =
        `<span class="n">${c.n}</span><span class="tt">${c.t}</span>`+
        (c.type==="tool" ? `<span class="badge tool">инструмент</span>` :
         c.ready ? `<span class="badge ready">готово</span>` : ``)+
        `<span class="done" title="пометить проведённым">✓</span>`;
      a.addEventListener("click", e=>{
        if(e.target.closest(".done")){ e.stopPropagation(); togglePlayed(idx); return; }
        go(idx); closeNav();
      });
      toc.appendChild(a);
    });
  });
}
function togglePlayed(idx){
  if(played.has(idx)) played.delete(idx); else played.add(idx);
  localStorage.setItem(STORE, JSON.stringify([...played]));
  const a = toc.querySelector(`a[data-idx="${idx}"]`);
  if(a){ a.classList.toggle("played", played.has(idx)); a.dataset.played = played.has(idx)?"1":""; }
  updateProgress();
}
function updateProgress(){
  $("#progDone").textContent = played.size;
  $("#progAll").textContent = flat.length;
  $("#progFill").style.width = (played.size/flat.length*100)+"%";
}
function renderPage(idx){
  const c = flat[idx];
  const typeRu = {lore:"лор",faction:"фракция",plot:"путь сюжета",quest:"квест",
    bestiary:"бестиарий",tool:"инструмент ведущего",map:"карта"}[c.type] || c.type;
  page.innerHTML =
    `<div class="margin-note">${c.m||""}</div>`+
    `<header class="pg-head">`+
      `<div class="bignum">${c.n}</div>`+
      `<div class="ttl"><div class="vol">${c.vol}</div><h2>${c.t}</h2>`+
        `<div class="kicker">${c.m||""}</div></div>`+
      `<div class="pg-tags"><span>${typeRu}</span>`+
        (c.type==="tool"?`<span class="tool">интерактив</span>`:``)+
        (c.ready?`<span class="ready">материал готов</span>`:``)+`</div>`+
    `</header>`+
    `<div class="pg-body">${c.body||""}`+
      (c.embed?`<div class="embed"><h4>${c.embed.h}</h4><p>${c.embed.p}</p></div>`:``)+
    `</div>`;
  page.classList.remove("turn"); void page.offsetWidth; page.classList.add("turn");
  toc.querySelectorAll("a").forEach(a=>a.classList.toggle("cur", +a.dataset.idx===idx));
  const curLink = toc.querySelector(`a[data-idx="${idx}"]`);
  if(curLink) curLink.scrollIntoView({block:"nearest", behavior:"smooth"});
  $("#pnPrev").disabled = idx<=0;
  $("#pnNext").disabled = idx>=flat.length-1;
  // ХУК ГЛАВЫ: модуль-инструмент оживляет контейнеры страницы (tome1.js и будущие модули)
  if(window.CH && typeof window.CH[c.n] === "function"){ try{ window.CH[c.n](page); }catch(e){ console.error("chapter init", c.n, e); } }
}
function go(idx){ if(idx<0||idx>=flat.length) return; cur=idx; renderPage(idx); location.hash = "ch-"+flat[idx].n; }
function closeNav(){ $("#book").classList.remove("nav-open"); }

$("#tocSearch").addEventListener("input", e=>{
  const q = e.target.value.trim().toLowerCase().replace(/ё/g,"е");
  toc.querySelectorAll("a").forEach(a=>{
    const txt = (a.querySelector(".tt").textContent+" "+(a.dataset.played?"проведено":"")).toLowerCase().replace(/ё/g,"е");
    a.classList.toggle("hide", q && !txt.includes(q));
  });
});
$("#pnPrev").addEventListener("click", ()=>go(cur-1));
$("#pnNext").addEventListener("click", ()=>go(cur+1));
$("#burger").addEventListener("click", ()=>$("#book").classList.toggle("nav-open"));
document.addEventListener("keydown", e=>{
  if(e.target.matches("input")) return;
  if(e.key==="ArrowRight") go(cur+1);
  if(e.key==="ArrowLeft")  go(cur-1);
});

